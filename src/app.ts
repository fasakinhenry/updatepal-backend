import cookieParser from "cookie-parser";
import cors from "cors";
import express from "express";
import helmet from "helmet";
import { env } from "@/core/env";
import { errorHandler, notFound } from "@/core/http";
import { authRoutes } from "@/modules/auth/routes";
import { documentRoutes } from "@/modules/documents/routes";
import { notificationRoutes } from "@/modules/notifications/notifications";
import { invitationRoutes, orgRoutes } from "@/modules/orgs/routes";
import { publishingRoutes } from "@/modules/publishing/routes";
import { updateRoutes } from "@/modules/updates/routes";
import { userRoutes } from "@/modules/users/routes";
import { mediaPublic, mediaRoutes } from "@/modules/media/routes";
import { subscribe } from "@/core/realtime";
import { requireAuth } from "@/core/security";
import { adminRoutes } from "@/modules/admin/routes";
import { paymentRoutes } from "@/modules/payments/routes";
import { systemRoutes } from "@/modules/system/routes";
import { settings } from "@/core/settings";
import { ApiError } from "@/core/http";
import { aiRoutes } from "@/modules/ai/routes";
import { insightRoutes, feedbackSubmit } from "@/modules/insights/routes";
import { messageRoutes } from "@/modules/messages/routes";
import { searchRoutes } from "@/modules/search/routes";
import { storyRoutes } from "@/modules/stories/routes";

export const app = express();
app.set("trust proxy", 1); // behind render's proxy, needed for correct rate limit ips
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true }));
app.use(cookieParser());
app.use((req, res, next) => ((req.path.endsWith("/content") && req.method === "PUT") || req.path.endsWith("/webhook") || (req.path === "/api/media" && req.method === "PUT") ? next() : express.json({ limit: "100kb" })(req, res, next)));

const api = express.Router();
api.get("/health", (_req, res) => res.json({ ok: true }));
api.use("/", systemRoutes);
// maintenance mode: everything except health, config, auth, the admin area and the payment webhook is paused
api.use(async (req, _res, next) => { try { if (!(await settings()).maintenance || /^\/(health|config|auth|admin|users\/me|payments\/(paypal\/)?webhook|media|events)/.test(req.path)) return next(); next(new ApiError(503, "maintenance", "updatebase is being updated. please try again soon.")); } catch (e) { next(e); } });
api.use("/media", mediaPublic);
api.use("/admin", adminRoutes);
api.get("/events", requireAuth, (req, res) => subscribe(req.userId!, res));
api.use("/media", mediaRoutes);
api.use("/payments", paymentRoutes);
api.use("/auth", authRoutes);
api.use("/users", userRoutes);
api.use("/orgs/by-handle/:handle/feedback", feedbackSubmit);
api.use("/orgs", orgRoutes);
api.use("/orgs/:orgId", publishingRoutes);
api.use("/orgs/:orgId", insightRoutes);
api.use("/orgs/:orgId/documents", documentRoutes);
api.use("/invitations", invitationRoutes);
api.use("/notifications", notificationRoutes);
api.use("/ai", aiRoutes);
api.use("/stories", storyRoutes);
api.use("/", searchRoutes);
api.use("/", messageRoutes);
api.use("/", updateRoutes);
app.use("/api", api);
app.use((_req, _res, next) => next(notFound("route")));
app.use(errorHandler);
